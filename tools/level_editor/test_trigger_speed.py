print("\n=== the authoring round trip ===")
with tempfile.TemporaryDirectory() as tmp:
    tmp = Path(tmp)
    lvl_dir = tmp / "levels" / "level1"
    lvl_dir.mkdir(parents=True)
    shutil.copy2(CANON, lvl_dir / "level.v6.json")
    lib_path = tmp / "encounter_library.v6.json"
    shutil.copy2(LIB, lib_path)
    doc_path = lvl_dir / "level.v6.json"
    base_out, fast_out, back_out = tmp / "a", tmp / "b", tmp / "c"

    ctl = EditorController.load(doc_path, library_path=lib_path)
    ctl.export(base_out, carry_enemies_from=PROD)
    # WHATEVER IS AUTHORED, EXPORTED FAITHFULLY -- not a frozen expectation of
    # what the author happens to have chosen.
    original_speeds = [t.resolved_speed for t in ctl.project.triggers]
    check("the exported column is exactly what the project holds",
          list(trig_speeds(base_out)) == original_speeds,
          str(original_speeds))
    check("...and every value is a legal choice",
          all(sp in C.SPEED_CHOICES for sp in trig_speeds(base_out)))

    ids = [t.wave_definition for t in ctl.project.triggers]
    shared = next(i for i in ids if ids.count(i) > 1)
    idx = [i for i, t in enumerate(ctl.project.triggers)
           if t.wave_definition == shared]
    # ALL FIVE, so the round trip covers the whole range and not just the ends.
    for i, sp in zip(idx, C.SPEED_CHOICES):
        ctl.update_trigger(i, speed=sp)
    ctl.save()

    ctl2 = EditorController.load(doc_path, library_path=lib_path)
    got = [t.resolved_speed for t in ctl2.project.triggers
           if t.wave_definition == shared]
    check("save + reload preserves every value that was set",
          got == list(C.SPEED_CHOICES[:len(got)]), str(got))
    check("...and the definition they share is still ONE definition",
          len([d for d in ctl2.project.wave_definitions if d.id == shared]) == 1)
    saved = json.loads(doc_path.read_text())
    check("the saved document states each trigger's speed outright",
          all("speed" in t for t in saved["triggers"]))
    lib_saved = json.loads(lib_path.read_text())
    check("...and the saved library states none",
          not any("speed" in x for x in lib_saved["waveDefinitions"]))

    ctl2.export(fast_out, carry_enemies_from=PROD)
    exported = trig_speeds(fast_out)
    check("the generated column carries the different speeds",
          [exported[i] for i in idx] == list(C.SPEED_CHOICES[:len(idx)]),
          str([exported[i] for i in idx]))
    check("...and untouched triggers kept whatever they had",
          all(exported[i] == original_speeds[i]
              for i in range(len(exported)) if i not in idx))

    # RESTORED TO WHAT THEY WERE, not to the default: the author may well have
    # authored a speed, and "put it back" has to mean put it back.
    for i in idx:
        ctl2.update_trigger(i, speed=original_speeds[i])
    ctl2.save()
    ctl3 = EditorController.load(doc_path, library_path=lib_path)
    ctl3.export(back_out, carry_enemies_from=PROD)
    names = [n for n in export_v6.GENERATED_NAMES if (base_out / n).exists()]
    differing = [n for n in names
                 if (base_out / n).read_bytes() != (back_out / n).read_bytes()]
    check("EVERY generated file is byte-identical after the round trip",
          not differing, ", ".join(differing) or f"{len(names)} files compared")
    again = tmp / "d"
    ctl3.export(again, carry_enemies_from=PROD)
    check("exporting twice is byte-identical",
          all((again / n).read_bytes() == (back_out / n).read_bytes()
              for n in names))

