"""Trigger-owned movement speed: model, migration, export, preview, widgets.

The runtime half is proved on the emulator in tests/test_trigger_speed.py and
the build-time flight validator in test_trigger_speed_validator.py. This proves
everything between the author's fingers and the generated bytes, and above all:

    THE SAME WAVE DEFINITION, USED BY TWO TRIGGERS, TRAVELS AT TWO
    DIFFERENT SPEEDS -- and is still ONE definition.

NOTHING PRODUCTION IS WRITTEN. Every save and export goes to a temporary
directory; the committed level documents and library are byte-compared at the
end.

THE WIDGET SECTION NEEDS A WORKING TK, which not every interpreter on a Mac
has. Run it with one that does:

    /usr/local/bin/python3 tools/level_editor/test_trigger_speed.py
"""
