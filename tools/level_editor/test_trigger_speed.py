# 5. PREVIEW PARITY -- the editor simulator honours the same scaling
# ===========================================================================
print("\n=== preview parity, per speed ===")
proj = EditorController.load(CANON, library_path=LIB).project


def distance(wave_id, speed, frames=60):
    """How far member 0 travels in `frames` frames at `speed`."""
    wave = ms.wave_by_id(proj, wave_id)
    sim = ms.simulate_wave(proj, wave, max_frames=frames + 2, speed=speed)
    path = sim.paths[0]
    a, b = path[0], path[min(frames, len(path) - 1)]
    return (b.x - a.x, b.y - a.y)


# PREDICTED FROM THE SCALED VELOCITY, NOT FROM THE SCALED DISTANCE. 1.25x of 6
# quarter pixels is 7, not 7.5 -- the engine has no half quarter-pixel -- so
# "the distance is 1.25x the distance" is false by design, and a test that
# checked it would be measuring the wrong thing and wanting a fudge factor.
# What must hold EXACTLY is that the wave travels at the velocity the scaling
# produces.
#
# THIRTY FRAMES KEEPS IT INSIDE THE FIRST LEG. `sweep` opens with a STRAIGHT of
# (6,0) for 34 frames; sampling past that mixes in the arc and the prediction
# stops being one multiplication.
STRAIGHT_FRAMES = 30
SWEEP_VX = 6
for n in C.SPEED_CHOICES:
    got = distance("sweep", n, frames=STRAIGHT_FRAMES)
    want_x = STRAIGHT_FRAMES * C.scale_velocity(SWEEP_VX, n) // 4
    check(f"{C.SPEED_LABELS[n]}: travels exactly its scaled velocity",
          got == (want_x, 0),
          f"got {got}, expected ({want_x}, 0) from "
          f"v={C.scale_velocity(SWEEP_VX, n)}")
check("1.00x is bit-identical to the unscaled engine",
      distance("sweep", 4, frames=STRAIGHT_FRAMES)
      == (STRAIGHT_FRAMES * SWEEP_VX // 4, 0))
check("2.00x travels exactly twice as far as 1.00x",
      distance("sweep", 8, frames=STRAIGHT_FRAMES)[0]
      == 2 * distance("sweep", 4, frames=STRAIGHT_FRAMES)[0],
      f"{distance('sweep', 4, frames=STRAIGHT_FRAMES)[0]} -> "
      f"{distance('sweep', 8, frames=STRAIGHT_FRAMES)[0]}")
check("the five speeds strictly increase in distance covered",
      all(distance("sweep", a, frames=STRAIGHT_FRAMES)[0]
          < distance("sweep", b, frames=STRAIGHT_FRAMES)[0]
          for a, b in zip(C.SPEED_CHOICES, C.SPEED_CHOICES[1:])),
      "; ".join(f"{C.SPEED_LABELS[n]}="
                f"{distance('sweep', n, frames=STRAIGHT_FRAMES)[0]}"
                for n in C.SPEED_CHOICES))

# an ARC, which has no authored velocity at all
arc = {n: distance("s", n, frames=40) for n in C.SPEED_CHOICES}
check("an ARC scales too, though it has no authored velocity",
      abs(arc[8][0]) + abs(arc[8][1]) > abs(arc[4][0]) + abs(arc[4][1]),
      f"1.00x {arc[4]} -> 2.00x {arc[8]}")
check("...monotonically across all five speeds",
      all(abs(arc[a][0]) + abs(arc[a][1]) <= abs(arc[b][0]) + abs(arc[b][1])
          for a, b in zip(C.SPEED_CHOICES, C.SPEED_CHOICES[1:])),
      "; ".join(f"{C.SPEED_LABELS[n]}={arc[n]}" for n in C.SPEED_CHOICES))

