if gui:
    import editor as ed
    ed.messagebox.showerror = lambda *a, **k: None
    ed.messagebox.showinfo = lambda *a, **k: None
    ed.messagebox.askyesno = lambda *a, **k: True
    import encounters_ui
    encounters_ui.messagebox.showerror = lambda *a, **k: None

    app = ed.LevelEditor(ed.find_repo_root())
    app.withdraw()                      # NEVER STEAL FOCUS
    app._open_encounters()
    w = app._encounters
    w.withdraw()
    app.update()

    def select(t):
        """Select THROUGH THE TREE, as a user does.

        Assigning w.sel_trigger directly does not survive the next
        app.update(): a pending <<TreeviewSelect>> re-derives it and overwrites
        the assignment.
        """
        i = w.controller.trigger_index_of(t)
        w.trig_tree.selection_set(str(i))
        w._trigger_selected()
        app.update()

    try:
        check("the trigger pane offers a movement speed", hasattr(w, "t_speed"))
        check("...showing the five friendly labels",
              list(w.t_speed["values"])
              == [C.SPEED_LABELS[v] for v in C.SPEED_CHOICES],
              str(list(w.t_speed["values"])))
        check("...and NOT the encoded integers",
              not any(x.strip().isdigit() for x in w.t_speed["values"]))
        check("the wave-definition pane offers no speed",
              "speed" not in w.w_fields and not hasattr(w, "w_speed"))

        # ---- TWO TRIGGERS, ONE DEFINITION, TWO SPEEDS ----------------
        trigs = w.controller.project.triggers
        groups = {}
        for i, t in enumerate(trigs):
            groups.setdefault(t.wave_definition, []).append(i)
        defn, group = next((k, v) for k, v in groups.items() if len(v) > 1)
        ta, tb = trigs[group[0]], trigs[group[1]]
        check(f"two triggers share the definition {defn!r}", True,
              f"rows {ta.world_progress} and {tb.world_progress}")

        select(ta)
        # ITS OWN SPEED, whatever the author has set it to -- not a literal.
        check("a trigger shows its own speed",
              w.t_speed.get() == C.SPEED_LABELS[ta.resolved_speed],
              f"shows {w.t_speed.get()!r}, is "
              f"{C.SPEED_LABELS[ta.resolved_speed]!r}")
        before_b = tb.resolved_speed
        w.t_speed.set("2.00x")
        w._trigger_apply()
        app.update()
        check("choosing 2.00x sets THIS trigger", ta.speed == 8, str(ta.speed))
        check("...AND LEAVES THE OTHER ON THE SAME DEFINITION ALONE",
              tb.resolved_speed == before_b,
              f"{before_b} -> {tb.resolved_speed}")
        check("...and the shared definition has no speed to change",
              not hasattr(next(x for x in w.controller.project.wave_definitions
                               if x.id == defn), "speed"))
        check("the edit marked the document dirty", app._is_dirty())

        select(tb)
        check("switching trigger shows the OTHER one's speed",
              w.t_speed.get() == C.SPEED_LABELS[before_b], w.t_speed.get())
        select(ta)
        check("...and switching back shows 2.00x again",
              w.t_speed.get() == "2.00x", w.t_speed.get())

        # ---- the workspace still works everywhere else ---------------
        for tab in range(3):
            w.tabs.select(tab)
            app.update()
        check("all three workspace tabs still select cleanly", True,
              "triggers / wave definitions / moves")
        check("the wave-definition pane still populates",
              bool(w.wave_list.size()))
        check("the movement-program pane still populates",
              bool(w.prog_list.size()))

        # ---- close and reopen, which is where the last regression hid
        w.destroy()
        app.update()
        app._open_encounters()
        w2 = app._encounters
        w2.withdraw()
        app.update()
        check("the Encounter window closes and reopens without a traceback",
              w2.winfo_exists() and hasattr(w2, "t_speed"))
        w2.destroy()
        app.update()
    finally:
        try:
            app.destroy()
        except Exception:                                       # noqa: BLE001
            pass

