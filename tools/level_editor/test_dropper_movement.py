# 8. THE PREVIEW CACHE -- every parameter that changes the geometry
# ===========================================================================
# WITHOUT THIS THE SCALING WORKS AND THE SCREEN DOES NOT. PreviewPanel._signature
# is compared to decide whether to re-fly; a trigger field the simulation reads
# and the signature omits leaves a correct simulation nobody ever asks for. The
# previous pass added resolved_speed for exactly this reason, and it must stay.
print("\n=== the preview cache notices every Dropper parameter ===")
try:
    import tkinter as tk
    import preview_ui
    from encounters_ui import EncounterWorkspace            # noqa: F401
    _tk = tk.Tk()
    _tk.withdraw()
except Exception as exc:                                    # noqa: BLE001
    check("a real Tk is available for the widget checks", False, str(exc))
else:
    ctl = EditorController(dropper_fixture())
    di = dropper_index(ctl.project)
    progs = [q.id for q in ctl.project.movement_programs]

    class _WS:
        def __init__(self, controller):
            self.controller = controller

    panel = preview_ui.PreviewPanel(_tk, _WS(ctl))
    panel.source = ("trigger", di)
    panel.preview_heading = 0

    def sig():
        return panel._signature()

    base = sig()
    check("a signature is produced for a Dropper trigger", base is not None)
    check("...and is stable when nothing changes", sig() == base)

    ctl.project.triggers[di].dropper_program = progs[0]
    on = sig()
    check("selecting an authored program changes the signature",
          on != base, "Legacy -> authored")
    ctl.project.triggers[di].dropper_program = progs[1]
    check("...and so does changing WHICH program", sig() != on)
    ctl.project.triggers[di].dropper_program = None
    check("...and returning to Legacy changes it back", sig() == base)

    ctl.project.triggers[di].dropper_side = "RIGHT"
    check("changing LEFT/RIGHT changes the signature: it moves the legacy path",
          sig() != base)
    ctl.project.triggers[di].dropper_side = "LEFT"

    # THE PREVIOUS PASS'S FIX, STILL IN PLACE.
    was = ctl.project.triggers[di].speed
    ctl.project.triggers[di].speed = 8
    check("changing the trigger's movement speed still changes the signature",
          sig() != base)
    ctl.project.triggers[di].speed = was

    # THE DROPPER'S PROGRAM STAGES ARE PART OF IT TOO: editing the path the
    # Dropper flies must invalidate the cache exactly as editing the
    # definition's own program does.
    ctl.project.triggers[di].dropper_program = progs[1]
    armed = sig()
    dprog = next(q for q in ctl.project.movement_programs if q.id == progs[1])
    first = dprog.stages[0]
    if hasattr(first, "frames"):
        first.frames = first.frames + 1
    else:
        first.steps = first.steps + 1
    check("editing a stage of the DROPPER'S program changes the signature",
          sig() != armed)

    # ---- the widgets ---------------------------------------------------
    print("\n=== the control, against real Tk ===")
    ctl2 = EditorController(dropper_fixture())
    di2 = dropper_index(ctl2.project)
    oi2 = other_index(ctl2.project)
    progs2 = [q.id for q in ctl2.project.movement_programs]
    # THE LITTLE OF THE MAIN WINDOW THE WORKSPACE ACTUALLY USES, exactly as
    # test_editor_workspace.py stubs it. Constructing the real workspace is the
    # point: a previous editor refactor produced a constructor/callback failure
    # that a model-only test could not have seen.
    class _Host(tk.Toplevel):
        def __init__(self, master, controller):
            super().__init__(master)
            self.withdraw()
            self.controller = controller
            self.project = controller.view
            self._encounters = None

        def _push_undo(self, before):
            pass

        def _update_document_ui(self):
            pass

        def _draw_level(self):
            pass

    host = _Host(_tk, ctl2)
    ws = EncounterWorkspace(host)
    ws.withdraw()
    ws.update_idletasks()

    def pick(i):
        ws.sel_trigger = i
        ws._refresh_trigger_detail()
        ws.update_idletasks()

    check("the workspace has a Dropper movement control",
          hasattr(ws, "t_dropmove"))
    check("...offering Legacy first, then this level's programs",
          list(ws.t_dropmove["values"])
          == [C.DROPPER_MOVEMENT_LEGACY] + progs2,
          ", ".join(ws.t_dropmove["values"]))
    pick(di2)
    check("a legacy Dropper shows Legacy selected",
          ws.t_dropmove.get() == C.DROPPER_MOVEMENT_LEGACY, ws.t_dropmove.get())
    check("...with the movement control enabled",
          str(ws.t_dropmove.cget("state")) == "readonly")
    check("...and LEFT/RIGHT enabled, because the legacy flight reads it",
          str(ws.t_side.cget("state")) == "readonly")

    ctl2.update_trigger(di2, dropper_program=progs2[0])
    pick(di2)
    check("an authored Dropper shows its program",
          ws.t_dropmove.get() == progs2[0], ws.t_dropmove.get())
    check("...and LEFT/RIGHT is DISABLED, because nothing reads it",
          str(ws.t_side.cget("state")) == "disabled")
    check("...and says so rather than leaving the author to infer it",
          "not used" in ws.t_side_note.cget("text").lower(),
          ws.t_side_note.cget("text"))
    check("...while the movement control explains what it does",
          "member 0" in ws.t_dropmove_note.cget("text"),
          ws.t_dropmove_note.cget("text")[:60])

    pick(oi2)
    check("a NON-Dropper trigger has the movement control disabled",
          str(ws.t_dropmove.cget("state")) == "disabled")
    check("...and is told why",
          "does not drop a token" in ws.t_dropmove_note.cget("text"),
          ws.t_dropmove_note.cget("text"))

    # SELECTING BACK AND FORTH, which is where a constructor/callback fault
    # would show as a stale control rather than as an exception.
    for _ in range(3):
        pick(di2)
        pick(oi2)
    pick(di2)
    check("repeated selection leaves the control showing the trigger's own "
          "answer",
          ws.t_dropmove.get() == progs2[0]
          and str(ws.t_dropmove.cget("state")) == "readonly")
